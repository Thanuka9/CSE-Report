def main() -> int:
    existing = [line for line in ITEMS.read_text(encoding="utf-8").splitlines() if line.strip()]
    kept = [
        line
        for line in existing
        if SourceTruthItem.model_validate_json(line).split != "HOLDOUT"
    ]
    items = holdout_items()
    lines = kept + [item.model_dump_json() for item in items]
    ITEMS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(items)} HOLDOUT items; total lines {len(lines)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
